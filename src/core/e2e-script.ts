/**
 * Turn a passing browser check into a Playwright test.
 *
 * `verify` walks a journey with click, fill, navigate, wait and assert steps. When every step of a run
 * succeeded, the steps are replayed as a `@playwright/test` file so the same journey runs in CI without a
 * model. Only a claim with an assertion step of its own is tagged: a replay of clicks proves nothing, so a
 * claim is never tagged for evidence the test does not check.
 *
 * Spec: specs/capabilities/agentic-verification.md
 */

export type ScriptStepKind = 'click' | 'fill' | 'navigate' | 'assertText' | 'waitFor';

export interface ScriptStep {
  kind: ScriptStepKind;
  /** What the planner said it was doing; kept as a comment. */
  description: string;
  selector?: string;
  /** Text to type, text that must be visible, or the path to open. */
  value?: string;
  /** For an assertion: the claim id it checks. */
  claim?: string;
}

export interface RenderInput {
  /** `capabilities/auth` */
  specKey: string;
  title: string;
  /** Where the journey started, as a URL or path; the test reads `BASE_URL` first. */
  startUrl: string;
  steps: ScriptStep[];
  /** Claim refs (`specKey#id`) that passed in the run. */
  passing: string[];
}

const q = (s: string): string => JSON.stringify(s);
const oneLine = (s: string): string => s.replace(/\s+/g, ' ').trim();

/** The claim refs a script's assertions back, among those that passed. */
export function assertedClaims(steps: ScriptStep[], specKey: string, passing: string[]): string[] {
  const asserted = new Set(steps.filter((s) => (s.kind === 'assertText' || s.kind === 'waitFor') && s.claim).map((s) => s.claim as string));
  return passing.filter((ref) => {
    const id = ref.includes('#') ? ref.slice(ref.indexOf('#') + 1) : ref;
    return ref.startsWith(`${specKey}#`) && asserted.has(id);
  });
}

/** A path under the project for a capability's generated test: `tests/e2e/auth.verify.spec.ts`. */
export function e2eTestPath(dir: string, specKey: string): string {
  const stem = specKey.replace(/^capabilities\//, '').replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '') || 'capability';
  return `${dir.replace(/\/+$/, '')}/${stem}.verify.spec.ts`;
}

/**
 * Render the Playwright test. Returns null when there is nothing worth replaying (no steps).
 * `redact` is applied to every value written; a step the redactor changes is refused, because a masked value
 * would make a test that cannot pass.
 */
export function renderPlaywrightTest(input: RenderInput, redact: (text: string) => string = (t) => t): string | null {
  if (input.steps.length === 0) return null;
  for (const s of input.steps) {
    for (const text of [s.value, s.selector]) if (text !== undefined && redact(text) !== text) return null;
  }
  const claims = assertedClaims(input.steps, input.specKey, input.passing);
  const tags = [...claims.map((c) => `@claim:${c}`), '@layer:e2e'].join(' ');
  const body: string[] = [`  await page.goto(process.env.BASE_URL ?? ${q(input.startUrl)});`];
  for (const s of input.steps) {
    body.push(`  // ${oneLine(s.description)}`);
    switch (s.kind) {
      case 'navigate':
        body.push(`  await page.goto(new URL(${q(s.value ?? '/')}, page.url()).toString());`);
        break;
      case 'fill':
        body.push(`  await page.fill(${q(s.selector ?? '')}, ${q(s.value ?? '')});`);
        break;
      case 'click':
        body.push(`  await page.click(${q(s.selector ?? '')});`);
        break;
      case 'waitFor':
        body.push(`  await page.waitForSelector(${q(s.selector ?? '')});`);
        break;
      case 'assertText':
        body.push(`  await expect(page.locator(${q(s.selector ?? 'body')})).toContainText(${q(s.value ?? '')});`);
        break;
    }
  }
  return [
    '// [layer: e2e]',
    `// Generated by \`specguard verify\` from a passing browser check of ${input.specKey}.`,
    '// It replays the steps the check took. Only claims with an assertion below are tagged. Edit freely.',
    "import { test, expect } from '@playwright/test';",
    '',
    `test(${q(`${oneLine(input.title)} ${tags}`)}, async ({ page }) => {`,
    ...body,
    '});',
    '',
  ].join('\n');
}
