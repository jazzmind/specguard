/**
 * Generated run state. These files are rewritten by pipeline runs, differ per
 * machine (or per run), and do not belong in version control. Configuration,
 * rules, plans and replay recordings are not listed. The proof ledger
 * (`.specguard/proofs.json`) is a local cache: what CI proved lives in git
 * notes (see the proof-store capability), so new repos ignore it. A repo that
 * already tracks it or `.specguard/trace.json` is moved by `specguard migrate`.
 *
 * Spec: specs/capabilities/platform-foundation.md
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';

/** Paths relative to the repo root, as `.gitignore` patterns. */
export const GENERATED_STATE_PATHS = [
  '.specguard/.env',
  '.specguard/activity-log.json',
  '.specguard/analysis.json',
  '.specguard/alignment.json',
  '.specguard/code-quality.json',
  '.specguard/dep-check.json',
  '.specguard/drift-registry.json',
  '.specguard/gaps.json',
  '.specguard/security.json',
  '.specguard/llm-usage.json',
  '.specguard/trace.json',
  '.specguard/proofs.json',
  '.specguard/rollup.json',
  '.specguard/security/scan.sarif',
  '.specguard/cache/',
  '.specguard/history/',
  '.specguard/traceability.json',
  '.specguard/traceability.csv',
  '.specguard/contracts.json',
  '.specguard/auth/',
  '.specguard/evidence/',
  '.specguard/runs/',
  '.specguard/reports/',
  '.specguard/report/',
  '.specguard/validation-history.json',
  '.specguard/ci/',
  '.specguard/coverage/',
  '.specguard/mutation/',
  '.specguard/publish/',
];

export const IGNORE_START = '# specguard:generated-state:start';
export const IGNORE_END = '# specguard:generated-state:end';

export interface IgnoreBlockOpts {
  /**
   * Also match `.specguard/` folders below the root: each path gets a leading any-depth glob (two stars and a slash). Used where
   * workspace repos live inside the git root (an overlay or monorepo), whose own `.specguard/`
   * folders a root-anchored pattern would miss.
   */
  nested?: boolean;
}

/** The ignore patterns, root-anchored or (with `nested`) matching at any depth. */
export function ignorePatterns(opts: IgnoreBlockOpts = {}): string[] {
  return opts.nested ? GENERATED_STATE_PATHS.map((p) => `**/${p}`) : [...GENERATED_STATE_PATHS];
}

export function renderIgnoreBlock(opts: IgnoreBlockOpts = {}): string {
  return [IGNORE_START, '# Generated by SpecGuard runs. Edit config, rules, plans and specs, not these.', ...ignorePatterns(opts), IGNORE_END, ''].join('\n');
}

/**
 * Add or refresh the managed block in `.gitignore` text. Lines outside the block
 * are untouched. A second call with the result returns it unchanged.
 */
export function applyIgnoreBlock(existing: string, opts: IgnoreBlockOpts = {}): string {
  const block = renderIgnoreBlock(opts);
  const start = existing.indexOf(IGNORE_START);
  const end = existing.indexOf(IGNORE_END);
  if (start !== -1 && end > start) {
    const after = existing.slice(end + IGNORE_END.length).replace(/^\r?\n/, '');
    return existing.slice(0, start) + block + after;
  }
  const base = existing.length === 0 || existing.endsWith('\n') ? existing : `${existing}\n`;
  return `${base}${base.length > 0 ? '\n' : ''}${block}`;
}

/**
 * True when a workspace manifest at `root` lists a repo or unit inside `root` (not `.` and not
 * outside it), so the ignore block must also cover nested `.specguard/` folders.
 */
export function hasNestedRepos(root: string): boolean {
  try {
    const raw = JSON.parse(readFileSync(path.join(root, '.specguard', 'workspace.json'), 'utf8')) as {
      repos?: Record<string, { path?: string }>;
      units?: Record<string, { path?: string }>;
    };
    const entries = [...Object.values(raw.repos ?? {}), ...Object.values(raw.units ?? {})];
    return entries.some((e) => {
      if (typeof e?.path !== 'string') return false;
      const rel = path.relative(root, path.resolve(root, e.path));
      return rel !== '' && !rel.startsWith('..') && !path.isAbsolute(rel);
    });
  } catch {
    return false;
  }
}
