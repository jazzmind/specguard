/**
 * The GitHub Actions workflows `specguard init --ci github` writes: one that gates pull requests and
 * comments on them, and one that opens remediation pull requests on a schedule.
 *
 * Pure text generation: `init` decides the options from the repo (package manager, monorepo, layers) and
 * never overwrites a workflow that is already there.
 *
 * Spec: specs/capabilities/integration-surfaces.md
 */
import { cliVersion } from './version.js';

export interface WorkflowOptions {
  /** The action to use, `owner/repo@ref`. Pin a release tag in real use. */
  actionRef?: string;
  /** Default branch: pushes to it run the gates too. */
  branch?: string;
  /** Command that installs the project's dependencies before the gates, when it has any. */
  install?: string;
  /** Workspace with package units: test only the units a pull request touched and the units that depend on them. */
  affected?: boolean;
  /** Layers claims must be proven in: `proof-incomplete` then fails the build. */
  requireLayers?: boolean;
  /** Offer a manual run of the browser `verify` gate against a URL. */
  verify?: boolean;
  /**
   * The SpecGuard release line the action installs, `major.minor` (`0.6`): a patch release is taken, a new minor is not
   * until the file says so. Default: this CLI's own `major.minor`.
   */
  version?: string;
  /** The repository records a check run binding each proof note to its digest (`proofStore.verify: check-run`): the workflow then needs `checks: write`. */
  attest?: boolean;
  /** Add the separate security job (the scan gate, code scanning upload, the optional model key). Default true. */
  security?: boolean;
}

const ACTION = 'jazzmind/specguard@main';

/** `0.4.0` -> `0.4`; anything that is not `major.minor[.patch]` is returned as given. */
export function minorOf(version: string): string {
  const m = /^v?(\d+)\.(\d+)(?:\.\d+)?(?:[-+].*)?$/.exec(version.trim());
  return m ? `${m[1]}.${m[2]}` : version.trim();
}

/**
 * The pull request workflow. One gating job, `prove`, runs the checks and `specguard ci run`, which proves what the pull
 * request changed, comments the proof packet, and pushes the proof note. It holds no model key. The security scan is a
 * separate job so a key never reaches the job that decides the merge.
 *
 * The job checks out the pull request head, not GitHub's merge ref, so the proof note sits on a real commit that a local
 * `check` finds and a squash merge can import by tree equality.
 */
export function renderPullRequestWorkflow(o: WorkflowOptions = {}): string {
  const branch = o.branch ?? 'main';
  const action = o.actionRef ?? ACTION;
  const version = minorOf(o.version ?? cliVersion());
  const failOn = ['missing-specs', ...(o.requireLayers ? ['proof-incomplete'] : []), 'test', 'prove'];
  const gates = ['check', 'test', 'prove', ...(o.requireLayers ? ['proof'] : []), 'publish'];
  const lines = [
    '# Generated by `specguard init --ci github`. It proves what a pull request changed, comments the proof packet on it,',
    '# and records the proof in the repository\'s git notes (refs/notes/specguard). Edit freely.',
    '#',
    '# The prove job holds no model API key: the gate is deterministic. Security findings run in their own job and do',
    '# not fail the build; add `scan` to `fail-on` once they are triaged.',
    '#',
    '# To make the verdict a rule, require the `prove` check in the default branch protection, and turn on',
    '# "Require review from Code Owners" so a change to specs/ needs someone other than its author.',
    'name: specguard',
    '',
    'on:',
    '  pull_request:',
    '  push:',
    `    branches: [${branch}]`,
    '  merge_group:',
    ...(o.verify
      ? [
          '  workflow_dispatch:',
          '    inputs:',
          '      verify-url:',
          "        description: 'Base URL of a running copy of the app. Runs the browser verify gate against it.'",
          '        required: false',
          "        default: ''",
        ]
      : ['  workflow_dispatch:']),
    '',
    'concurrency:',
    '  group: specguard-${{ github.ref }}',
    '  cancel-in-progress: true',
    '',
    '# contents: write pushes the proof note; pull-requests: write reads reviews and keeps the packet comment up to date.',
    '# A run from a fork gets a read-only token: it proves everything and writes the packet to the job summary only.',
    'permissions:',
    '  contents: write',
    '  pull-requests: write',
    ...(o.attest ? ['  checks: write   # the specguard/proof-note check run that binds each note to its digest'] : []),
    '',
    'jobs:',
    '  prove:',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 30',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '        with:',
    '          ref: ${{ github.event.pull_request.head.sha || github.sha }}   # the pull request head, not the merge ref',
    '          fetch-depth: 0   # the base commit and the proof notes must be reachable',
    "      - run: git fetch --no-tags origin '+refs/notes/specguard:refs/notes/specguard' || echo 'no proof notes yet'",
    ...(o.install ? ['      - uses: actions/setup-node@v4', '        with:', "          node-version: '20'", `      - run: ${o.install}`] : []),
    `      - uses: ${action}`,
    '        with:',
    `          version: '${version}'`,
    `          gates: ${gates.join(',')}`,
    `          fail-on: ${failOn.join(',')}`,
    `          affected: '${o.affected ? 'true' : 'false'}'`,
    '          github-token: ${{ secrets.GITHUB_TOKEN }}',
  ];
  if (o.security !== false) {
    lines.push(
      '',
      '  security:',
      '    runs-on: ubuntu-latest',
      '    timeout-minutes: 30',
      '    permissions:',
      '      contents: read',
      '      security-events: write',
      '    steps:',
      '      - uses: actions/checkout@v4',
      ...(o.install ? ['      - uses: actions/setup-node@v4', '        with:', "          node-version: '20'", `      - run: ${o.install}`] : []),
      `      - uses: ${action}`,
      '        with:',
      `          version: '${version}'`,
      '          gates: scan',
      '          fail-on: none',
      "          sarif: 'true'",
      "          comment: 'false'",
      '        env:',
      '          # Add an LLM key in the repository secrets to let the spec-level security review run:',
      '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}',
    );
  }
  if (o.verify) {
    lines.push(
      '',
      '  verify:',
      "    if: ${{ github.event_name == 'workflow_dispatch' && github.event.inputs.verify-url != '' }}",
      '    runs-on: ubuntu-latest',
      '    timeout-minutes: 30',
      '    permissions:',
      '      contents: read',
      '    steps:',
      '      - uses: actions/checkout@v4',
      `      - uses: ${action}`,
      '        with:',
      `          version: '${version}'`,
      '          gates: verify',
      '          fail-on: verify',
      '          install-playwright: \'true\'',
      '          validate-url: ${{ github.event.inputs.verify-url }}',
      "          comment: 'false'",
      '        env:',
      '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}',
    );
  }
  return `${lines.join('\n')}\n`;
}

/** The scheduled workflow that opens a remediation pull request per advisory group. */
export function renderRemediateWorkflow(o: WorkflowOptions & { autoMerge?: boolean } = {}): string {
  const lines = [
    '# Generated by `specguard init --ci github`. Opens one pull request per advisory group on weekdays.',
    '# A pull request is a normal one only when every proof was shown to still hold; otherwise it is a draft that lists the',
    '# differences. App-code fixes are never merged for you.',
    ...(o.autoMerge
      ? [
          '#',
          '# Auto-merge is on for dependency fixes that keep every proof (see `remediate.autoMerge` in .specguard/config.json).',
          '# It only arms GitHub auto-merge on a protected branch whose required checks must pass, and it needs a token that',
          '# can trigger workflows: pull requests opened with GITHUB_TOKEN do not run CI. Add a SPECGUARD_BOT_TOKEN secret.',
        ]
      : []),
    'name: specguard-remediate',
    '',
    'on:',
    '  schedule:',
    "    - cron: '17 5 * * 1-5'   # weekdays, 05:17 UTC",
    '  workflow_dispatch:',
    '    inputs:',
    '      args:',
    "        description: 'Extra specguard remediate arguments, for example --advisory GHSA-xxxx --allow-major'",
    '        required: false',
    "        default: ''",
    '',
    'concurrency:',
    '  group: specguard-remediate-${{ github.repository }}',
    '  cancel-in-progress: false',
    '',
    'permissions:',
    '  contents: write',
    '  pull-requests: write',
    '',
    'jobs:',
    '  remediate:',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 60',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '        with:',
    '          fetch-depth: 0   # worktrees and branch checks need history',
    ...(o.install ? ['      - uses: actions/setup-node@v4', '        with:', "          node-version: '20'"] : []),
    `      - uses: ${o.actionRef ?? ACTION}`,
    '        with:',
    '          mode: remediate',
    o.autoMerge ? '          github-token: ${{ secrets.SPECGUARD_BOT_TOKEN || secrets.GITHUB_TOKEN }}' : '          github-token: ${{ secrets.GITHUB_TOKEN }}',
    `          remediate-args: \${{ github.event.inputs.args || '--min-severity high${o.autoMerge ? ' --auto-merge' : ''}' }}`,
    "          open-pr: 'true'",
    '        env:',
    '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}',
  ];
  return `${lines.join('\n')}\n`;
}

/** Workflow path (repo-relative) for each file `init --ci github` writes. */
export const WORKFLOW_FILES = { pullRequest: '.github/workflows/specguard.yml', remediate: '.github/workflows/specguard-remediate.yml' } as const;

/** The install command for the project's package manager, from the lockfiles it has. */
export function installCommandFor(has: (file: string) => boolean): string | undefined {
  if (has('pnpm-lock.yaml')) return 'corepack enable && pnpm install --frozen-lockfile';
  if (has('yarn.lock')) return 'yarn install --frozen-lockfile';
  if (has('package-lock.json')) return 'npm ci';
  if (has('package.json')) return 'npm install';
  return undefined;
}
