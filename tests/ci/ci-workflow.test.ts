import { describe, expect, it } from 'vitest';
import { parse as parseYaml } from 'yaml';

import { minorOf, renderPullRequestWorkflow } from '../../src/core/ci-workflow.js';
import { cliVersion } from '../../src/core/version.js';

type Step = { uses?: string; run?: string; with?: Record<string, string | number>; env?: Record<string, string> };
type Workflow = {
  on: Record<string, unknown>;
  permissions: Record<string, string>;
  jobs: Record<string, { if?: string; permissions?: Record<string, string>; steps: Step[] }>;
};
const parsed = (text: string): Workflow => parseYaml(text) as Workflow;
const action = (steps: Step[]): Step | undefined => steps.find((s) => s.uses?.startsWith('jazzmind/specguard'));

/** The workflow `specguard init --ci github` writes for a Node repo, line by line. A change to it is a decision, not an accident. */
const GOLDEN = [
  '# Generated by `specguard init --ci github`. It proves what a pull request changed, comments the proof packet on it,',
  '# and records the proof in the repository\'s git notes (refs/notes/specguard). Edit freely.',
  '#',
  '# The prove job holds no model API key: the gate is deterministic. Security findings run in their own job and do',
  '# not fail the build; add `scan` to `fail-on` once they are triaged.',
  '#',
  '# To make the verdict a rule, require the `prove` check in the default branch protection, and turn on',
  '# "Require review from Code Owners" so a change to specs/ needs someone other than its author.',
  'name: specguard',
  '',
  'on:',
  '  pull_request:',
  '  push:',
  '    branches: [main]',
  '  merge_group:',
  '  workflow_dispatch:',
  '',
  'concurrency:',
  '  group: specguard-${{ github.ref }}',
  '  cancel-in-progress: true',
  '',
  '# contents: write pushes the proof note; pull-requests: write reads reviews and keeps the packet comment up to date.',
  '# A run from a fork gets a read-only token: it proves everything and writes the packet to the job summary only.',
  'permissions:',
  '  contents: write',
  '  pull-requests: write',
  '',
  'jobs:',
  '  prove:',
  '    runs-on: ubuntu-latest',
  '    timeout-minutes: 30',
  '    steps:',
  '      - uses: actions/checkout@v4',
  '        with:',
  '          ref: ${{ github.event.pull_request.head.sha || github.sha }}   # the pull request head, not the merge ref',
  '          fetch-depth: 0   # the base commit and the proof notes must be reachable',
  '      - run: git fetch --no-tags origin \'+refs/notes/specguard:refs/notes/specguard\' || echo \'no proof notes yet\'',
  '      - uses: actions/setup-node@v4',
  '        with:',
  '          node-version: \'20\'',
  '      - run: npm ci',
  '      - uses: jazzmind/specguard@main',
  '        with:',
  '          version: \'0.6\'',
  '          gates: check,test,prove,publish',
  '          fail-on: missing-specs,test,prove',
  '          affected: \'false\'',
  '          github-token: ${{ secrets.GITHUB_TOKEN }}',
  '',
  '  security:',
  '    runs-on: ubuntu-latest',
  '    timeout-minutes: 30',
  '    permissions:',
  '      contents: read',
  '      security-events: write',
  '    steps:',
  '      - uses: actions/checkout@v4',
  '      - uses: actions/setup-node@v4',
  '        with:',
  '          node-version: \'20\'',
  '      - run: npm ci',
  '      - uses: jazzmind/specguard@main',
  '        with:',
  '          version: \'0.6\'',
  '          gates: scan',
  '          fail-on: none',
  '          sarif: \'true\'',
  '          comment: \'false\'',
  '        env:',
  '          # Add an LLM key in the repository secrets to let the spec-level security review run:',
  '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}',
].join('\n');

describe('the generated pull request workflow [ci-workflow-golden]', () => {
  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('is exactly the documented text for a Node repository', () => {
    expect(renderPullRequestWorkflow({ install: 'npm ci', branch: 'main', version: '0.6.2' })).toBe(`${GOLDEN}\n`);
  });

  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('checks out the pull request head with full history, not the merge ref, and fetches the proof notes', () => {
    const steps = parsed(renderPullRequestWorkflow()).jobs.prove.steps;
    expect(steps[0]).toMatchObject({ uses: 'actions/checkout@v4', with: { ref: '${{ github.event.pull_request.head.sha || github.sha }}', 'fetch-depth': 0 } });
    expect(steps[1]?.run).toContain("+refs/notes/specguard:refs/notes/specguard");
    expect(steps[1]?.run).toContain('|| echo');
  });

  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('passes no model API key to the job that gates the merge, and keeps it on the separate security job', () => {
    const text = renderPullRequestWorkflow({ verify: true });
    const wf = parsed(text);
    for (const step of wf.jobs.prove.steps) expect(step.env).toBeUndefined();
    const gate = action(wf.jobs.prove.steps);
    expect(JSON.stringify(gate)).not.toMatch(/API_KEY/);
    expect(action(wf.jobs.security.steps)?.env).toEqual({ ANTHROPIC_API_KEY: '${{ secrets.ANTHROPIC_API_KEY }}' });
    expect(wf.jobs.security.permissions).toEqual({ contents: 'read', 'security-events': 'write' });
    expect(wf.jobs.verify.permissions).toEqual({ contents: 'read' });
    expect(parsed(renderPullRequestWorkflow({ security: false })).jobs.security).toBeUndefined();
  });

  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('asks for checks: write only when proof notes are attested, and always for the rights a note and a comment need', () => {
    expect(parsed(renderPullRequestWorkflow()).permissions).toEqual({ contents: 'write', 'pull-requests': 'write' });
    expect(parsed(renderPullRequestWorkflow({ attest: true })).permissions).toEqual({ contents: 'write', 'pull-requests': 'write', checks: 'write' });
  });

  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('runs the prove gate, fails the build on it, and also listens to the merge queue', () => {
    const wf = parsed(renderPullRequestWorkflow({ requireLayers: false }));
    expect(Object.keys(wf.on)).toContain('merge_group');
    const gate = action(wf.jobs.prove.steps);
    expect(String(gate?.with?.gates).split(',')).toEqual(expect.arrayContaining(['check', 'test', 'prove', 'publish']));
    expect(String(gate?.with?.['fail-on']).split(',')).toContain('prove');
    // The legacy ledger thresholds are gone: a gitignored ledger is not in a fresh checkout.
    expect(String(gate?.with?.['fail-on'])).not.toMatch(/proof-stale|proof-failed/);
  });

  // [claims: capabilities/integration-surfaces#ci-workflow-prove]
  it('pins the installed SpecGuard by the package minor', () => {
    expect(minorOf('0.4.0')).toBe('0.4');
    expect(minorOf('v1.12.3-beta.1')).toBe('1.12');
    expect(minorOf('latest')).toBe('latest');
    const wf = parsed(renderPullRequestWorkflow({ version: '0.6.9' }));
    expect(action(wf.jobs.prove.steps)?.with?.version).toBe('0.6');
    expect(action(parsed(renderPullRequestWorkflow()).jobs.prove.steps)?.with?.version).toBe(minorOf(cliVersion()));
  });
});
