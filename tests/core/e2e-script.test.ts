import { describe, expect, it } from 'vitest';

import { assertedClaims, e2eTestPath, renderPlaywrightTest, type ScriptStep } from '../../src/core/e2e-script.js';

const steps: ScriptStep[] = [
  { kind: 'fill', description: 'enter the code', selector: '#code', value: '123456' },
  { kind: 'click', description: 'press go', selector: 'button[type="submit"]' },
  { kind: 'navigate', description: 'open the home page', value: '/home?x=1' },
  { kind: 'waitFor', description: 'wait for the menu', selector: '#menu', claim: 'logout-clears-session' },
  { kind: 'assertText', description: 'welcome shows\nacross two lines', selector: '#msg', value: 'Welcome "Sam"', claim: 'login-valid-code' },
];
const input = {
  specKey: 'capabilities/auth',
  title: 'Auth',
  startUrl: 'http://localhost:3000/',
  steps,
  passing: ['capabilities/auth#login-valid-code', 'capabilities/auth#logout-clears-session', 'capabilities/auth#unasserted'],
};

describe('rendering a Playwright test from a check [e2e-render]', () => {
  // [claims: capabilities/agentic-verification#verify-emits-playwright]
  it('replays every step, escapes values, and starts from BASE_URL when set', () => {
    const text = renderPlaywrightTest(input) as string;
    expect(text.split('\n').slice(0, 5)).toEqual([
      '// [layer: e2e]',
      '// Generated by `specguard verify` from a passing browser check of capabilities/auth.',
      '// It replays the steps the check took. Only claims with an assertion below are tagged. Edit freely.',
      "import { test, expect } from '@playwright/test';",
      '',
    ]);
    expect(text).toContain('await page.goto(process.env.BASE_URL ?? "http://localhost:3000/");');
    expect(text).toContain('await page.fill("#code", "123456");');
    expect(text).toContain('await page.click("button[type=\\"submit\\"]");');
    expect(text).toContain('await page.goto(new URL("/home?x=1", page.url()).toString());');
    expect(text).toContain('await page.waitForSelector("#menu");');
    expect(text).toContain('await expect(page.locator("#msg")).toContainText("Welcome \\"Sam\\"");');
    expect(text).toContain('// welcome shows across two lines'); // a comment cannot swallow the next line
  });

  // [claims: capabilities/agentic-verification#verify-emits-playwright]
  it('tags only the passing claims that have an assertion of their own', () => {
    const text = renderPlaywrightTest(input) as string;
    expect(text).toContain('@claim:capabilities/auth#login-valid-code');
    expect(text).toContain('@claim:capabilities/auth#logout-clears-session');
    expect(text).not.toContain('unasserted');
    expect(text).toContain('@layer:e2e');
    expect(assertedClaims(steps, 'capabilities/auth', ['capabilities/other#login-valid-code'])).toEqual([]);
    expect(assertedClaims(steps.slice(0, 3), 'capabilities/auth', input.passing)).toEqual([]); // clicks prove nothing
    const none = renderPlaywrightTest({ ...input, steps: steps.slice(0, 3) }) as string;
    expect(none).not.toContain('@claim:');
  });

  // [claims: capabilities/agentic-verification#verify-emits-playwright]
  it('writes nothing for no steps, and refuses a step whose value the redactor would change', () => {
    expect(renderPlaywrightTest({ ...input, steps: [] })).toBeNull();
    expect(renderPlaywrightTest(input, (t) => t.replace('123456', '[redacted]'))).toBeNull();
    expect(renderPlaywrightTest(input, (t) => t)).not.toBeNull();
  });

  // [claims: capabilities/agentic-verification#verify-emits-playwright]
  it('names the file after the capability', () => {
    expect(e2eTestPath('tests/e2e', 'capabilities/auth')).toBe('tests/e2e/auth.verify.spec.ts');
    expect(e2eTestPath('tests/e2e/', 'capabilities/user profile')).toBe('tests/e2e/user-profile.verify.spec.ts');
    expect(e2eTestPath('e2e', 'journeys/x')).toBe('e2e/journeys-x.verify.spec.ts');
  });
});
